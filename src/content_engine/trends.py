"""Idea suggestions for Shorts — NOT a virality guarantee.

Sources (fail-closed honesty):
- offline niche seeds (always)
- optional Google Trends RSS (public, no TikTok scrape / no cookie bots)
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
from urllib.parse import quote_plus

from content_engine.hook_score import score_script
from content_engine.pipeline import PACKAGE_ROOT
from content_engine.script_writer import offline_topic_script

# Lightweight public RSS (ideas only — not proof of future views)
GT_RSS = "https://trends.google.com/trends/trendingsearches/daily/rss?geo={geo}"

OFFLINE_SEEDS_EN = [
    "Why silent green checks hide broken systems",
    "Three signs your automation is lying to you",
    "Fail-closed checks vs marketing screenshots",
    "Laptop Shorts pipeline without a GPU",
    "What evidence packs mean for Agent Skills",
]

OFFLINE_SEEDS_RU = [
    "Почему тихий зелёный статус врёт",
    "Три признака, что автоматизация врёт",
    "Fail-closed против маркетинговых скриншотов",
    "Шортс на ноутбуке без GPU",
    "Что evidence-pack даёт Agent Skills",
]


def _fetch_google_trends(geo: str = "US", *, limit: int = 12) -> list[dict[str, Any]]:
    try:
        import httpx
    except ImportError:
        return []
    url = GT_RSS.format(geo=quote_plus(geo.upper()))
    try:
        with httpx.Client(timeout=20.0, follow_redirects=True) as client:
            r = client.get(url, headers={"User-Agent": "dup-content-engine/0.1"})
            if r.status_code >= 400:
                return []
            root = ET.fromstring(r.text)
    except Exception:  # noqa: BLE001
        return []

    items: list[dict[str, Any]] = []
    for item in root.findall(".//item"):
        title = (item.findtext("title") or "").strip()
        if not title:
            continue
        items.append(
            {
                "topic": title,
                "source": "google_trends_rss",
                "geo": geo.upper(),
            }
        )
        if len(items) >= limit:
            break
    return items


def suggest_ideas(
    *,
    language: str = "en",
    geo: str = "US",
    limit: int = 8,
    online: bool = True,
    niche: str | None = None,
    out_path: Path | None = None,
) -> dict[str, Any]:
    """Rank idea topics with hook heuristic. Ideas ≠ guaranteed virality."""
    lang = (language or "en").lower().split("-")[0]
    seeds = list(OFFLINE_SEEDS_RU if lang == "ru" else OFFLINE_SEEDS_EN)
    if niche:
        seeds.insert(0, niche.strip())

    raw: list[dict[str, Any]] = [{"topic": t, "source": "offline_seed"} for t in seeds]
    online_note = "offline_only"
    if online:
        trends = _fetch_google_trends("RU" if lang == "ru" else geo, limit=max(limit, 8))
        if trends:
            raw.extend(trends)
            online_note = "google_trends_rss+offline"
        else:
            online_note = "offline_fallback_trends_unreachable"

    # Dedupe by lower topic
    seen: set[str] = set()
    uniq: list[dict[str, Any]] = []
    for row in raw:
        key = re.sub(r"\s+", " ", row["topic"].strip().lower())
        if key in seen:
            continue
        seen.add(key)
        uniq.append(row)

    ranked: list[dict[str, Any]] = []
    for row in uniq:
        script = offline_topic_script(row["topic"], language=lang)
        hook = score_script(script)
        ranked.append(
            {
                **row,
                "language": lang,
                "hook_score": hook.get("score"),
                "hook_label": hook.get("label"),
                "title_preview": script.title,
            }
        )
    ranked.sort(key=lambda r: r.get("hook_score") or 0, reverse=True)
    ranked = ranked[: max(1, limit)]

    topics_lines = "\n".join(
        [
            "# Generated by dup-content ideas — NOT a virality claim",
            f"# {datetime.now(timezone.utc).isoformat()} source={online_note}",
            "",
            *[r["topic"] for r in ranked],
            "",
        ]
    )
    result: dict[str, Any] = {
        "ok": True,
        "honesty": (
            "Idea suggestions only. Hook score is a heuristic. "
            "Trending search ≠ guaranteed views or ALLOW growth."
        ),
        "source": online_note,
        "language": lang,
        "count": len(ranked),
        "ideas": ranked,
        "next": "python -m content_engine day <topics.txt> --language "
        f"{lang} --out out/series",
    }
    if out_path:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(topics_lines, encoding="utf-8")
        (out_path.with_suffix(".json")).write_text(
            json.dumps(result, indent=2) + "\n", encoding="utf-8"
        )
        result["topics_file"] = str(out_path)
        result["json"] = str(out_path.with_suffix(".json"))
    else:
        default = PACKAGE_ROOT / "out" / "ideas" / "topics.ideas.txt"
        default.parent.mkdir(parents=True, exist_ok=True)
        default.write_text(topics_lines, encoding="utf-8")
        result["topics_file"] = str(default)
    return result
